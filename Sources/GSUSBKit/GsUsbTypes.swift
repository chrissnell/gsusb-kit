import Foundation

// The seam between `GsUsbDevice` and whatever is consuming it. These types
// exist so the driver owes nothing to any particular application's model
// layer: a host that already has a `Frame` type maps `GsUsbFrame` onto it in
// one initialiser, and a host that does not can use these directly.

// MARK: - Frames

/// One CAN frame the adapter delivered, already decoded and timestamped.
///
/// Classical and CAN FD frames arrive through this one type, with `fd` saying
/// which. They are not separated because a CAN FD bus carries both — a
/// classical frame on an FD link is an ordinary thing to see, and splitting
/// the stream in two would make a recording's interleaving something the host
/// had to reassemble.
///
/// `timestampNs` is `CLOCK_REALTIME` nanoseconds since the Unix epoch, mapped
/// from whichever of the two sources the connection negotiated: the adapter's
/// own microsecond counter when it has one, host USB-completion time when it
/// does not. `GsUsbDevice.timestampMode` says which, and a host that records
/// frames is expected to record that answer alongside them — the two are not
/// interchangeable, and a smeared capture has to stay identifiable afterwards.
public struct GsUsbFrame: Sendable, Equatable {
    public var timestampNs: Int64
    /// Generated by the driver and restarted at 0 for each connection, so a
    /// hole in it is impossible by construction. The adapter's own overflow
    /// report (`GsUsbStatistics.readStarvationEvents`) is what says frames
    /// were lost, not a gap here.
    public var seq: UInt64
    /// Flag bits already stripped: 11-bit for standard frames, 29-bit for
    /// extended.
    public var canID: UInt32
    public var extended: Bool
    public var rtr: Bool
    /// gs_usb delivers CAN error frames as host frames with the error flag
    /// set, so they arrive here rather than through a separate channel.
    public var err: Bool
    /// A CAN FD frame: `data` may be up to 64 bytes, and only the lengths CAN
    /// FD can express appear (0–8, 12, 16, 20, 24, 32, 48, 64).
    public var fd: Bool
    /// The data phase ran at the connection's data bitrate rather than at the
    /// arbitration rate. Only ever true on a CAN FD frame, and recorded
    /// separately from `fd` because the two are genuinely different frames on
    /// the wire — a 64-byte frame sent entirely at 500 kbit/s is legal.
    public var bitRateSwitch: Bool
    /// The *transmitting* node was error-passive. Set by that node's
    /// controller, so this is information about some other device on the bus
    /// and not about this adapter.
    public var errorStateIndicator: Bool
    public var data: [UInt8]
    /// True when this host transmitted the frame and the adapter echoed it
    /// back, rather than it having been observed from another node. A
    /// recording that mixed the two silently would let an injection be read
    /// back as a bus response.
    public var tx: Bool
    /// The live connection's description — `"gs_usb SH-C30x #0001 500k
    /// listen-only hw-ts"`.
    ///
    /// Carried on the frame rather than read back off the device because it is
    /// only known once the handshake has negotiated a timestamp source, and a
    /// consumer must not have to await the actor mid-publish to label a frame
    /// it has already been handed.
    public var sourceDescription: String

    /// The three CAN FD flags default to `false`, so a host that only ever
    /// builds classical frames — a test fixture, a replay of a pre-FD capture
    /// — constructs one exactly as it always did.
    public init(
        timestampNs: Int64,
        seq: UInt64,
        canID: UInt32,
        extended: Bool,
        rtr: Bool,
        err: Bool,
        fd: Bool = false,
        bitRateSwitch: Bool = false,
        errorStateIndicator: Bool = false,
        data: [UInt8],
        tx: Bool,
        sourceDescription: String
    ) {
        self.timestampNs = timestampNs
        self.seq = seq
        self.canID = canID
        self.extended = extended
        self.rtr = rtr
        self.err = err
        self.fd = fd
        self.bitRateSwitch = bitRateSwitch
        self.errorStateIndicator = errorStateIndicator
        self.data = data
        self.tx = tx
        self.sourceDescription = sourceDescription
    }
}

/// A frame the host wants to put on the wire.
///
/// Deliberately not `GsUsbFrame`. That type carries `timestampNs`, `seq` and
/// `sourceDescription`, which only the driver can legitimately fill, so
/// accepting one here would invite callers to invent a sequence number.
public struct GsUsbOutboundFrame: Sendable, Equatable {
    public var canID: UInt32
    public var extended: Bool
    public var rtr: Bool
    /// Send this as a CAN FD frame. Requires a connection opened with
    /// `GsUsbOptions.FrameFormat.canFD`; `send` throws
    /// `GsUsbTransmitError.canFDNotEnabled` otherwise rather than downgrading
    /// the frame to classical and putting a different frame on the bus.
    public var fd: Bool
    /// Run the data phase at the data bitrate. CAN FD only, and not implied by
    /// `fd`: an FD frame without it is sent entirely at the arbitration rate,
    /// which is what you want on a link whose other nodes cannot switch.
    public var bitRateSwitch: Bool
    /// At most 8 bytes classical; on a CAN FD frame, one of the lengths CAN FD
    /// can express — 0–8, 12, 16, 20, 24, 32, 48 or 64.
    public var data: [UInt8]

    /// `errorStateIndicator` has no outbound counterpart on purpose — the
    /// controller sets ESI from its own error state, so a host-supplied value
    /// would be a field that looks settable and is not.
    public init(
        canID: UInt32,
        extended: Bool = false,
        rtr: Bool = false,
        fd: Bool = false,
        bitRateSwitch: Bool = false,
        data: [UInt8] = []
    ) {
        self.canID = canID
        self.extended = extended
        self.rtr = rtr
        self.fd = fd
        self.bitRateSwitch = bitRateSwitch
        self.data = data
    }
}

// MARK: - Frame delivery

/// Where `GsUsbDevice` hands each decoded frame, in arrival order.
///
/// A protocol rather than an `AsyncStream` because the ordering guarantee is
/// load-bearing for transmit: `send` returns only once the device has echoed
/// the frame back, and the echo is published *before* the send is resolved, so
/// a caller that sends and then reads its own recording cannot race its own
/// frame. Handing frames to a stream the host drains on its own schedule would
/// lose exactly that.
///
/// `consume` is awaited by the read loop, so an implementation that suspends
/// holds the loop up. Enqueue and return; do not do the host's own work here.
public protocol GsUsbFrameConsumer: Sendable {
    func consume(_ frame: GsUsbFrame) async
}

// MARK: - Connection state

/// Published connection state.
///
/// Four cases cover a USB adapter without extension: `connecting(attempt:)`
/// spans enumerate, open and configure, and `disconnected(reason:)` spans
/// surprise removal, bus-off and a refused claim.
public enum GsUsbConnectionState: Sendable, Equatable, Hashable {
    case idle
    case connecting(attempt: Int)
    case connected
    case disconnected(reason: String)

    public var isConnected: Bool {
        if case .connected = self { return true }
        return false
    }

    public var isConnecting: Bool {
        if case .connecting = self { return true }
        return false
    }
}

// MARK: - Notices

/// Something the driver saw that a recording should be annotated with: an
/// adapter-reported receive overflow, a controller entering a degraded error
/// state, a connection that fell back to host-completion timestamps.
///
/// Free text, because the set is open and the host's job is to surface it
/// rather than to branch on it. The two timestamps are both carried because
/// only one of them is always available: `canTimestampNs` is the capture time
/// of the frame nearest the event and is `nil` before the first frame has
/// arrived, while `localTimestampNs` comes from the driver's own monotonic
/// clock and is always present.
public struct GsUsbNotice: Sendable, Equatable, Hashable {
    public var label: String
    public var canTimestampNs: Int64?
    public var localTimestampNs: Int64

    public init(label: String, canTimestampNs: Int64?, localTimestampNs: Int64) {
        self.label = label
        self.canTimestampNs = canTimestampNs
        self.localTimestampNs = localTimestampNs
    }
}

// MARK: - Statistics

/// Cumulative counters for one `GsUsbDevice`, carried across reconnects.
public struct GsUsbStatistics: Sendable, Equatable {
    public var framesReceived: UInt64 = 0
    /// Frames this host put on the wire and the adapter confirmed by echo.
    /// Stays zero on a listen-only connection, which cannot have one.
    public var framesTransmitted: UInt64 = 0
    /// Bulk-IN bytes that would not decode as `gs_host_frame`: a trailing
    /// fragment too short to be the frame its header describes, or a frame
    /// with an impossible DLC. Counted once per undecodable region, not per
    /// byte.
    public var decodeFailures: UInt64 = 0
    /// Frames the driver knows it never saw, where the loss happened below it —
    /// the adapter reporting its receive FIFO overflowed. Since `seq` is
    /// generated locally this is the *only* upward signal that frames were
    /// lost, so a host that ignores it will read a saturated reader as a clean
    /// capture.
    public var readStarvationEvents: UInt64 = 0
    public var reconnectCount: Int = 0
    public var lastSeq: UInt64 = 0
    /// The driver clock's monotonic reading when the most recent frame was
    /// published.
    public var lastFrameLocalNs: Int64 = 0
    /// The capture timestamp of the same frame `lastFrameLocalNs` was stamped
    /// for. The two are only a usable clock-offset pair because both are taken
    /// in the read loop, before the frame reaches any consumer buffer.
    public var lastFrameCanTsNs: Int64 = 0

    public init() {}
}

// MARK: - Reconnect

/// Reconnect delays, escalating then capped.
public struct GsUsbBackoffPolicy: Sendable, Equatable {
    public let delays: [Duration]

    public init(delays: [Duration]) {
        self.delays = delays
    }

    public static let `default` = GsUsbBackoffPolicy(
        delays: [.seconds(1), .seconds(2), .seconds(5)]
    )

    /// `attempt` is 1-based. Beyond the table, the last delay repeats.
    /// `nil` means "do not retry" (an empty table, used by tests).
    public func delay(forAttempt attempt: Int) -> Duration? {
        guard !delays.isEmpty else { return nil }
        let index = min(max(attempt, 1) - 1, delays.count - 1)
        return delays[index]
    }
}
